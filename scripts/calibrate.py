"""Reverse-engineer hidden rules from calculator probes (research/probes.csv).

For every probe the calculator's answer is inverted:
    implied FOIR     = (EMI on max_loan_shown + existing_emi) / income
    implied multiple = max_loan_shown / income
Probes are grouped by lender and income band. A tight FOIR spread across tenures means FOIR is
the binding rule; a constant multiple across tenures means a salary-multiple cap binds.
For lenders in the rule table the engine is replayed on the same inputs, so the report shows how
close the model gets to the lender's own calculator.
"""
import csv
from statistics import median

from _path import ROOT
from loan_engine.engine import emi_room, multiple_cap
from loan_engine.finance import pmt, pv
from loan_engine.rules import load_lenders


def load_probes():
    with open(ROOT / "research/probes.csv", newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k in ("net_income", "existing_emi", "tenure_months", "max_loan_shown"):
            r[k] = int(r[k])
        r["calc_cap"] = int(r.get("calc_cap") or 0)
        r["rate_pct"] = float(r["rate_pct"])
    return rows


def implied(r):
    emi = pmt(r["max_loan_shown"], r["rate_pct"], r["tenure_months"])
    return (emi + r["existing_emi"]) / r["net_income"], r["max_loan_shown"] / r["net_income"]


def band(income):
    return "<=50k" if income <= 50_000 else "50k-1L" if income < 100_000 else ">=1L"


def replay(r, lenders):
    """Max loan from the lender's sizing rules on the calculator's own inputs (its rate, tenure and cap).

    This checks the rule the calculator reveals (FOIR band, salary multiple), not product pricing: a
    calculator uses one fixed rate, while the engine prices each applicant within the lender's band.
    """
    lender = lenders[r["lender_id"]].for_segments(set())
    income, emi = r["net_income"], r["existing_emi"]
    _, _, room = emi_room(lender, income, emi)
    limits = [pv(max(room, 0), r["rate_pct"], r["tenure_months"]),
              multiple_cap(lender, income, emi, r["tenure_months"])[1]]
    if r["calc_cap"]:
        limits.append(r["calc_cap"])
    return int(min(limits))


def main():
    lenders = load_lenders()
    probes = [r for r in load_probes() if r["eligible_shown"] == "Y"]
    groups = {}
    for r in probes:
        foir, mult = implied(r)
        r["foir"], r["mult"] = foir, mult
        groups.setdefault((r["lender_id"], band(r["net_income"])), []).append(r)

    md = ["# Calculator calibration report", "",
          "Generated by `python scripts/calibrate.py` from `research/probes.csv`.", "",
          "## Implied parameters", "",
          "| Lender | Income band | Probes | Implied FOIR (median) | FOIR spread | Implied multiple | Reading |",
          "|---|---|---|---|---|---|---|"]
    for (lid, b), rs in sorted(groups.items()):
        foirs = [r["foir"] for r in rs]
        spread = max(foirs) - min(foirs)
        if len(rs) < 2:
            reading = "single probe: add tenure/EMI sweeps to confirm which rule binds"
        else:
            reading = "FOIR binds (consistent)" if spread < 0.02 else "check: multiple/cap may bind"
        md.append(f"| {lid} | {b} | {len(rs)} | {median(foirs):.1%} | {spread:.1%} | "
                  f"{median(r['mult'] for r in rs):.1f}x | {reading} |")

    md += ["", "## Replay: model vs lender calculator", "",
           "| Probe | Lender | Calculator max loan | Model max loan | Error |", "|---|---|---|---|---|"]
    replayed = [r for r in probes if r["lender_id"] in lenders and r.get("replay", "Y") == "Y"]
    for r in replayed:
        model = replay(r, lenders)
        md.append(f"| {r['probe_id']} | {r['lender_id']} | {r['max_loan_shown']:,} | {model:,} | "
                  f"{(model - r['max_loan_shown']) / r['max_loan_shown']:+.1%} |")
    if not replayed:
        md.append("| - | - | - | - | No lender-specific probes captured yet (see research/HOW_TO_PROBE.md) |")
    (ROOT / "research/calibration_report.md").write_text("\n".join(md) + "\n")
    print(f"Calibrated {len(probes)} probes in {len(groups)} groups; wrote research/calibration_report.md")


if __name__ == "__main__":
    main()
