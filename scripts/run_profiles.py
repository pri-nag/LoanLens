"""Run every test profile through the engine and write test_profiles/results.md and results.json."""
import json

from _path import ROOT
from loan_engine.engine import Profile, assess
from loan_engine.report import profile_markdown, result_to_dict
from loan_engine.rules import load_lenders


def main():
    lenders = load_lenders()
    profiles = [Profile(**p) for p in json.loads((ROOT / "test_profiles/profiles.json").read_text())]
    results = [assess(p, lenders) for p in profiles]
    out = ROOT / "test_profiles"
    (out / "results.json").write_text(
        json.dumps([result_to_dict(r) for r in results], indent=2, default=str) + "\n")

    summary = ["# Test profile results", "",
               "Generated by `python scripts/run_profiles.py`. Rule data as read on 2026-10-11 and 2026-10-12.", "",
               "| Profile | Scenario | Decision | # lenders | Best option | Max loan (best) | Rate | Main blocker |",
               "|---|---|---|---|---|---|---|---|"]
    for r in results:
        p = r["profile"]
        blocker = next(iter(r["blocker_counts"]), "-")
        if r["eligible"]:
            b = r["best"]
            summary.append(f"| {p.profile_id} | {p.description} | Eligible | {len(r['approving_lenders'])} | "
                           f"{b.lender_name} | Rs {b.max_loan:,} | {b.rate_pct}% | {blocker} |")
        else:
            summary.append(f"| {p.profile_id} | {p.description} | **Not eligible** | 0 | - | - | - | {blocker} |")
    summary += ["", "## Detail per profile", ""] + [profile_markdown(r) for r in results]
    (out / "results.md").write_text("\n".join(summary))
    print(f"Wrote {len(results)} profiles to test_profiles/")


if __name__ == "__main__":
    main()
